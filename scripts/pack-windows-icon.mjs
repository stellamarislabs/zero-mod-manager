// Build every Windows ICO frame from the generated, shared-brand PNGs.
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
const sizes = [32, 64, 128, 256];
const names = ['32x32.png', '64x64.png', '128x128.png', '128x128@2x.png'];
const frames = names.map(name => readFileSync(`src-tauri/icons/${name}`));
const header = Buffer.alloc(6 + frames.length * 16);
header.writeUInt16LE(1, 2);
header.writeUInt16LE(frames.length, 4);
let offset = header.length;
frames.forEach((frame, i) => {
  if (frame.readUInt32BE(16) !== sizes[i] || frame.readUInt32BE(20) !== sizes[i]) throw new Error('Unexpected icon dimensions');
  const at = 6 + i * 16;
  header[at] = header[at + 1] = sizes[i] % 256;
  header.writeUInt16LE(1, at + 4);
  header.writeUInt16LE(32, at + 6);
  header.writeUInt32LE(frame.length, at + 8);
  header.writeUInt32LE(offset, at + 12);
  offset += frame.length;
});
const ico = Buffer.concat([header, ...frames]);
const sha256 = value => createHash('sha256').update(value).digest('hex');
const resourceName = `zero-brand-${sha256(ico).slice(0, 12)}.ico`;
writeFileSync('src-tauri/icons/icon.ico', ico);
writeFileSync('src-tauri/icons/app-icon.svg', readFileSync('src/assets/icon.svg'));
writeFileSync('src-tauri/icons/brand-manifest.json', JSON.stringify({
  source: 'src/assets/icon.svg', sourceSha256: sha256(readFileSync('src/assets/icon.svg')),
  icoSha256: sha256(ico), resourceName,
  frames: Object.fromEntries(names.map((name, i) => [name, sha256(frames[i])])),
}, null, 2) + '\n');
writeFileSync('src-tauri/icons/windows-icon.nsh', `; Generated by scripts/pack-windows-icon.mjs.\n!define ZERO_BRAND_ICON "${resourceName}"\n`);
const configPath = 'src-tauri/tauri.conf.json';
const config = JSON.parse(readFileSync(configPath, 'utf8'));
// A content-addressed shell resource avoids the stale EXE-icon cache on upgrade.
config.bundle.resources = { ...config.bundle.resources, 'icons/icon.ico': resourceName };
writeFileSync(configPath, JSON.stringify(config, null, 2) + '\n');
console.log(`Windows ICO: 32, 64, 128 and 256px from shared brand PNGs; shell resource ${resourceName}.`);
